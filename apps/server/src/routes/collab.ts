import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { CollabCreateBodySchema, CollabRevisionBodySchema, type Song } from '@chordifree/contracts';
import { ApiError } from '../errors';
import { MAX_SHARES_PER_USER, type CollabStore } from '../services/collab';
import { resolveNickname, type ProfileStore } from '../services/profiles';
import { requireUser } from './profile';

export interface CollabRouterDeps {
  collab: CollabStore;
  profiles: ProfileStore;
}

/** Share identifiers are 32 lowercase hex characters. */
const SHARE_ID_PATTERN = /^[0-9a-f]{32}$/;
/** Revision identifiers are UUIDs generated by the server. */
const REVISION_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
/** A shared snapshot is chords plus lyrics; anything bigger is abuse, not a song. */
const MAX_SONG_BYTES = 256 * 1024;

function shareIdFrom(value: string): string {
  if (!SHARE_ID_PATTERN.test(value)) {
    throw new ApiError('NOT_FOUND', 'The shared song does not exist');
  }
  return value;
}

function revisionIdFrom(value: string): string {
  if (!REVISION_ID_PATTERN.test(value)) {
    throw new ApiError('NOT_FOUND', 'The shared version does not exist');
  }
  return value;
}

function songBytes(song: unknown): number {
  try {
    return Buffer.byteLength(JSON.stringify(song) ?? '');
  } catch {
    return Number.POSITIVE_INFINITY;
  }
}

function requireSongSize(song: unknown): void {
  if (songBytes(song) > MAX_SONG_BYTES) {
    throw new ApiError('FILE_TOO_LARGE', 'The song is too large to share');
  }
}

/**
 * A shared song is a small revision history. Every signed-in member of the
 * allowlist who has the link can read it and publish a new revision, and the
 * server rejects writes based on a stale revision (last writer never wins by
 * accident).
 */
export function createCollabRouter({ collab, profiles }: CollabRouterDeps): Router {
  const router = Router();
  const readLimiter = rateLimit({
    windowMs: 60_000,
    limit: 120,
    standardHeaders: true,
    legacyHeaders: false,
    keyGenerator: (req) => req.authUser?.uid ?? req.ip ?? 'unknown',
    message: { code: 'RATE_LIMITED', message: 'Too many shared song requests' },
  });
  const writeLimiter = rateLimit({
    windowMs: 60_000,
    limit: 40,
    standardHeaders: true,
    legacyHeaders: false,
    keyGenerator: (req) => req.authUser?.uid ?? req.ip ?? 'unknown',
    message: { code: 'RATE_LIMITED', message: 'Too many collaborative edits' },
  });

  router.post('/', writeLimiter, async (req, res, next) => {
    try {
      const user = requireUser(req.authUser);
      const parsed = CollabCreateBodySchema.safeParse(req.body);
      if (!parsed.success) {
        throw new ApiError('INVALID_REQUEST', 'The shared song is not valid');
      }
      const owned = await collab.countOwnedBy(user.uid);
      if (owned >= MAX_SHARES_PER_USER) {
        throw new ApiError('INVALID_REQUEST', 'Too many shared songs for this account');
      }
      requireSongSize(parsed.data.song);
      const nickname = await resolveNickname(profiles, user);
      const share = await collab.create(
        { uid: user.uid, nickname },
        parsed.data.song as unknown as Song,
      );
      res.status(201).json(share);
    } catch (error) {
      next(error);
    }
  });

  router.get('/:id', readLimiter, async (req, res, next) => {
    try {
      requireUser(req.authUser);
      res.json(await collab.get(shareIdFrom(req.params.id)));
    } catch (error) {
      next(error);
    }
  });

  router.get('/:id/revisions/:revisionId', readLimiter, async (req, res, next) => {
    try {
      requireUser(req.authUser);
      res.json(
        await collab.getRevision(shareIdFrom(req.params.id), revisionIdFrom(req.params.revisionId)),
      );
    } catch (error) {
      next(error);
    }
  });

  router.post('/:id/revisions', writeLimiter, async (req, res, next) => {
    try {
      const user = requireUser(req.authUser);
      const parsed = CollabRevisionBodySchema.safeParse(req.body);
      if (!parsed.success) {
        throw new ApiError('INVALID_REQUEST', 'The shared version is not valid');
      }
      const share = await collab.get(shareIdFrom(req.params.id));
      const song = parsed.data.song as unknown as Song;
      requireSongSize(song);
      if (song.id !== share.songId) {
        throw new ApiError('INVALID_REQUEST', 'The shared version belongs to another song');
      }
      const nickname = await resolveNickname(profiles, user);
      const revision = await collab.append(
        shareIdFrom(req.params.id),
        { uid: user.uid, nickname },
        parsed.data.baseRevisionId,
        song,
      );
      res.status(201).json(revision);
    } catch (error) {
      next(error);
    }
  });

  return router;
}
